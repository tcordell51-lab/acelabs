#!/usr/bin/env node
// gate-cut-map.mjs : the approved cut list, as redirects. No file is deleted, except a removed
// page whose row carries deleted: true.
//
//   node scripts/gate-cut-map.mjs           check (part of npm test)
//   node scripts/gate-cut-map.mjs --write   rewrite the generated block in _redirects
//   node scripts/gate-cut-map.mjs --pending list merges that are waiting on a fold
//
// scripts/cut-map.json has one row per student page (135):
//   keep    the page stays; its clean address ("to") answers with a 302 to where it lives today
//   merge   the old address is forced (301) to its target, but only once fold = "done"
//   remove  the old address is forced (301) to its target
// The check fails if any of the 135 old addresses, or any clean address, does not land
// on a real file within two hops, or if a kept page is caught by a forced rule.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REDIRECTS = path.join(ROOT, '_redirects');
const BEGIN = '# ---- BEGIN cut list (generated by scripts/gate-cut-map.mjs --write) ----';
const END = '# ---- END cut list ----';
const map = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'cut-map.json'), 'utf8'));

function addresses(rel) {
  const a = ['/' + rel];
  if (rel.endsWith('/index.html')) { const d = '/' + rel.slice(0, -'index.html'.length); a.push(d, d.replace(/\/$/, '')); }
  else if (rel.endsWith('.html')) a.push('/' + rel.slice(0, -5));
  return a;
}
function fileFor(addr) {
  let p = addr.split('#')[0].split('?')[0];
  if (p === '/') p = '/index.html';
  const f = path.join(ROOT, p);
  try { if (fs.statSync(f).isDirectory()) return fs.existsSync(path.join(f, 'index.html')) ? path.join(p, 'index.html') : null; return p; } catch (e) { /* not a file */ }
  return fs.existsSync(f + '.html') ? p + '.html' : null;
}
const active = map.pages.filter((p) => p.action === 'remove' || (p.action === 'merge' && p.fold === 'done'));
const pending = map.pages.filter((p) => p.action === 'merge' && p.fold !== 'done');
const kept = map.pages.filter((p) => p.action === 'keep');

function block() {
  const L = [BEGIN, '# Do not edit by hand: change scripts/cut-map.json and run this script with --write.', '# Old addresses of removed and merged pages (forced: the files still exist).'];
  for (const p of active) for (const a of addresses(p.path)) L.push(`${a}  ${p.now}  301!`);
  L.push('# Clean addresses of kept pages. 302 for now: the files have not moved yet.');
  for (const [clean, now] of Object.entries(map.clean)) if (clean !== now && !fileFor(clean)) L.push(`${clean}  ${now}  302`);
  L.push(END);
  return L.join('\n');
}

const args = process.argv.slice(2);
if (args.includes('--pending')) { for (const p of pending) console.log(`${p.path}  ->  ${p.to}   (${p.fold_note})`); console.log(pending.length + ' merges waiting on a fold'); process.exit(0); }
let text = fs.readFileSync(REDIRECTS, 'utf8');
if (args.includes('--write')) {
  const b = block(), i = text.indexOf(BEGIN), j = text.indexOf(END);
  text = (i >= 0 && j > i) ? text.slice(0, i) + b + text.slice(j + END.length) : text.replace(/\n*$/, '\n') + b + '\n';
  fs.writeFileSync(REDIRECTS, text);
}

// resolve an address the way the host will: forced rules first, then files, then other rules
const rules = text.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#')).map((l) => l.split(/\s+/)).filter((p) => p.length >= 3).map((p) => ({ from: p[0], to: p[1], forced: /!$/.test(p[2]), status: parseInt(p[2], 10) }));
const same = (a, b) => a === b || a.replace(/\/$/, '') === b.replace(/\/$/, '');
function match(rule, addr) { if (rule.from.endsWith('/*')) { const base = rule.from.slice(0, -1); return addr.startsWith(base) || addr === base.slice(0, -1); } return same(rule.from, addr); }
function resolve(addr) {
  let cur = addr.split('#')[0];
  for (let hop = 0; hop <= 2; hop++) {
    const forced = rules.find((r) => r.forced && match(r, cur));
    if (forced) { cur = forced.to.split('#')[0]; continue; }
    const f = fileFor(cur); if (f) return { file: f, hops: hop };
    const soft = rules.find((r) => !r.forced && match(r, cur));
    if (!soft) return { file: null, hops: hop };
    cur = soft.to.split('#')[0];
  }
  return { file: null, hops: 3 };
}
const problems = [];
if (map.pages.length !== 135) problems.push('cut-map.json must list 135 pages, has ' + map.pages.length);
for (const p of map.pages) {
  // Files may be deleted only when the row says remove and the address still redirects
  // (booster-map.html, deleted 2026-11-16 on Thomas's rule: no competitor material in the repo).
  if (!fs.existsSync(path.join(ROOT, p.path)) && !(p.action === 'remove' && p.deleted)) problems.push('file was deleted: ' + p.path);
  for (const a of addresses(p.path)) {
    const r = resolve(a);
    if (!r.file) problems.push(`old address ${a} lands nowhere`);
    else if (p.action === 'keep' && !same('/' + p.path, r.file) && r.file !== fileFor('/' + p.path)) problems.push(`kept page ${a} is redirected to ${r.file}`);
    else if (active.includes(p) && r.file === fileFor('/' + p.path)) problems.push(`${a} should redirect but still serves itself (run --write)`);
    else if (pending.includes(p) && r.file !== fileFor('/' + p.path)) problems.push(`${a} is redirected before its fold is done`);
  }
}
for (const [clean] of Object.entries(map.clean)) { const r = resolve(clean); if (!r.file) problems.push(`clean address ${clean} lands nowhere`); }
if (problems.length) { console.error(`gate-cut-map: ${problems.length} problem(s)`); for (const x of problems.slice(0, 40)) console.error('  ' + x); process.exit(1); }
console.log(`gate-cut-map: OK. 135 old addresses and ${Object.keys(map.clean).length} clean addresses land on a real page within two hops. Keep ${kept.length}; redirected now ${active.length}; merges waiting on a fold ${pending.length}.`);
