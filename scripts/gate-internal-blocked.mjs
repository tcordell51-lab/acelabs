#!/usr/bin/env node
// gate-internal-blocked.mjs : internal material must never be served to students.
//
//   node scripts/gate-internal-blocked.mjs            check: exit 1 if an internal path is not
//                                                     covered by a forced rule in _redirects, or
//                                                     if a forced rule would catch a student page
//   node scripts/gate-internal-blocked.mjs --write    rewrite the generated block in _redirects
//   node scripts/gate-internal-blocked.mjs --list     print every internal path
//
// The publish directory is the repo root, so every file ships unless a forced rule
// (status with "!") shadows it. A rule without "!" loses to an existing file.
// Dependency-free.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REDIRECTS = path.join(ROOT, '_redirects');
const TARGET = '/ace-labs.html';
const BEGIN = '# ---- BEGIN internal pages (generated by scripts/gate-internal-blocked.mjs --write) ----';
const END = '# ---- END internal pages ----';

// Whole folders that hold only internal files.
const INTERNAL_DIRS = [
  'tests/bio', 'tests/pat', 'tests/shell', 'tests/ochem2026', 'tests/qr-formats',
  'tools/gc/research', 'tools/qr/research',
  'tools/rc/verification', 'tools/rc/scripts',
  'tools/mock/verification', 'tools/minitests/source',
  'tools/qr/proposals/agent-10-sarah',
  'tools/qr/proposals/agent-01-audit',
  'tools/qr/proposals/sprint-c-beta-audit',
  'tools/content'
];

// Internal or production pages that no student page loads.
const INTERNAL_PAGES = [
  'tools/gc/tiktoks/index.html',
  'tools/gc/tiktoks/scripts.html',
  'tools/gc/tiktoks/voiceover-studio.html',
  'tools/qr/tiktoks/index.html',
  'tools/qr/tiktoks/voiceover-studio.html',
  'tricks/series/voiceover-studio.html',
  'tricks/videos/voiceover-studio.html',
  'tools/ochem/roots/dev.html',
  'tools/ochem/tree/dev.html',
  'tools/ochem/tree/smiles.html'
];

// Production clip pages that a student page loads as its "Watch" explainer.
// Blocking them would break that button, so they stay served until the clips
// move into one player. Listed here so the gap is explicit, not forgotten.
const EMBEDDED_CLIPS = {
  'tools/bio/sliding-filament-tiktok.html': 'tools/bio/bio-physiology.html',
  'tools/gc/tiktoks/buffers-hh-tiktok.html': 'tools/gc/index.html',
  'tools/gc/tiktoks/gibbs-quadrant-tiktok.html': 'tools/gc/index.html',
  'tools/gc/tiktoks/ksp-common-ion-tiktok.html': 'tools/gc/index.html',
  'tools/gc/tiktoks/lewis-five-steps-tiktok.html': 'tools/gc/index.html',
  'tools/gc/tiktoks/q-vs-k-tiktok.html': 'tools/gc/index.html',
  'tools/gc/tiktoks/weak-acid-sqrt-tiktok.html': 'tools/gc/index.html',
  'tools/gc/tiktoks/topic-tiktok.html': 'tools/gc/index.html',
  'tools/ochem/v2/tiktoks/eas-directors-tiktok.html': 'tools/ochem/v2/index.html',
  'tools/qr/tiktoks/count-pc-collapse-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/harm-distance-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/p-cond-bayes-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/sarah-baseball-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/sarah-c-method-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/sarah-dice-pyramid-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/sarah-pretend-100-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/sarah-shield-tornado-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/sarah-work-rate-trap-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/zscore-bell-tiktok.html': 'tools/qr/index.html',
  'tools/qr/tiktoks/topic-tiktok.html': 'tools/qr/index.html',
  'tricks/series/topic-tiktok.html': 'tools/gc/index.html'
};

// Retired student pages that are forced to their replacement on purpose.
const RETIRED = ['calendar.html', 'mocks-catalog.html', 'unified-mock.html'];

// Folders already covered by older forced rules, or never part of the student site.
const SKIP = /^(node_modules|\.git|\.netlify|\.claude|netlify|test-screenshots|dist-astro|astro-proto)(\/|$)/;
const ALREADY = /^(docs|specs|research|plans)(\/|$)/;

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    const rel = path.relative(ROOT, p).split(path.sep).join('/');
    if (SKIP.test(rel)) continue;
    if (e.isDirectory()) walk(p, out); else out.push(rel);
  }
  return out;
}

const files = walk(ROOT);
const inDir = (rel) => INTERNAL_DIRS.find((d) => rel.startsWith(d + '/'));
// Internal single files: every markdown or python file in the served tree, plus the listed pages.
const singles = files.filter((f) => !ALREADY.test(f) && !inDir(f) && (/\.(md|py)$/i.test(f) || INTERNAL_PAGES.includes(f)));
const internalAll = files.filter((f) => !ALREADY.test(f) && (inDir(f) || singles.includes(f)));

// Every address a file answers on: the file, the extensionless form, the folder form.
function addresses(rel) {
  const a = ['/' + rel];
  if (rel.endsWith('/index.html')) { const d = '/' + rel.slice(0, -'index.html'.length); a.push(d, d.replace(/\/$/, '')); }
  else if (rel.endsWith('.html')) a.push('/' + rel.slice(0, -5));
  return a;
}

function generatedBlock() {
  const lines = [BEGIN,
    '# Forced so an existing file cannot shadow the rule. Do not edit by hand:',
    '# change the lists in scripts/gate-internal-blocked.mjs and run it with --write.'];
  for (const d of INTERNAL_DIRS) lines.push(`/${d}/*  ${TARGET}  301!`);
  for (const s of singles.sort()) for (const a of addresses(s)) lines.push(`${a}  ${TARGET}  301!`);
  lines.push(END);
  return lines.join('\n');
}

function forcedRules(text) {
  const rules = [];
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const parts = line.split(/\s+/);
    if (parts.length < 3 || !/!$/.test(parts[parts.length - 1])) continue;
    rules.push(parts[0]);
  }
  return rules;
}
function matches(rule, addr) {
  if (rule.endsWith('/*')) { const base = rule.slice(0, -1); return addr.startsWith(base) || addr === base.slice(0, -1); }
  return rule === addr || rule === addr.replace(/\/$/, '') || rule.replace(/\/$/, '') === addr;
}

const args = process.argv.slice(2);
let text = fs.readFileSync(REDIRECTS, 'utf8');

if (args.includes('--list')) { for (const f of internalAll) console.log(f); console.log(`${internalAll.length} internal paths`); process.exit(0); }

if (args.includes('--write')) {
  const block = generatedBlock();
  const i = text.indexOf(BEGIN), j = text.indexOf(END);
  text = (i >= 0 && j > i) ? text.slice(0, i) + block + text.slice(j + END.length) : text.replace(/\n*$/, '\n') + block + '\n';
  fs.writeFileSync(REDIRECTS, text);
  console.log(`_redirects: wrote ${block.split('\n').length - 4} forced rules for ${internalAll.length} internal paths`);
}

const rules = forcedRules(text);
const problems = [];
for (const f of internalAll) for (const a of addresses(f)) if (!rules.some((r) => matches(r, a))) problems.push(`not blocked: ${a}`);
for (const p of INTERNAL_PAGES) if (!files.includes(p)) problems.push(`listed internal page does not exist: ${p}`);
for (const [clip, host] of Object.entries(EMBEDDED_CLIPS)) {
  if (!files.includes(clip)) problems.push(`listed clip does not exist: ${clip}`);
  else if (!files.includes(host) || !fs.readFileSync(path.join(ROOT, host), 'utf8').includes('tiktok')) problems.push(`clip ${clip}: host page ${host} no longer loads clips; move the clip to INTERNAL_PAGES`);
}
// A student page must never be caught by a forced rule.
const student = files.filter((f) => f.endsWith('.html') && !ALREADY.test(f) && !internalAll.includes(f) && !RETIRED.includes(f));
for (const f of student) for (const a of addresses(f)) { const r = rules.find((x) => matches(x, a)); if (r) problems.push(`student page ${a} is caught by forced rule ${r}`); }
// Anything that looks like production tooling must be on one of the two lists.
for (const f of files) if (/(tiktok|voiceover-studio|\/dev\.html$)/.test(f) && f.endsWith('.html') && !internalAll.includes(f) && !(f in EMBEDDED_CLIPS)) problems.push(`unlisted production page: ${f} (add it to INTERNAL_PAGES or EMBEDDED_CLIPS)`);

if (problems.length) { console.error(`gate-internal-blocked: ${problems.length} problem(s)`); for (const p of problems.slice(0, 60)) console.error('  ' + p); process.exit(1); }
console.log(`gate-internal-blocked: OK. ${internalAll.length} internal paths blocked (${INTERNAL_DIRS.length} folders, ${singles.length} single files); ${student.length} student pages untouched; ${Object.keys(EMBEDDED_CLIPS).length} embedded clip pages still served.`);
